
import re
from pathlib import Path

from sqlalchemy import text
from database import engine


def find_products_array():
    project_root = Path(__file__).resolve().parent.parent

    # Find the JavaScript file containing the existing catalogue.
    for js_file in (project_root / "js").glob("*.js"):
        source = js_file.read_text(encoding="utf-8")

        match = re.search(
            r"\bvar\s+PRODUCTS\s*=\s*\[(.*?)\]\s*;",
            source,
            re.DOTALL,
        )

        if match:
            return match.group(1), js_file

    raise RuntimeError(
        "Could not find 'var PRODUCTS = [...]' in any file in the js folder."
    )


def parse_products(array_content):
    products = []

    # Each catalogue entry is a flat JavaScript object.
    objects = re.findall(r"\{([^{}]*)\}", array_content, re.DOTALL)

    for obj in objects:
        fields = dict(
            re.findall(
                r"(\w+)\s*:\s*'((?:\\.|[^'\\])*)'",
                obj,
            )
        )

        # Skip anything that isn't a product record.
        required = {"name", "category", "description", "image"}
        if not required.issubset(fields):
            continue

        products.append({
            "name": fields["name"],
            "category": fields["category"],
            "description": fields["description"],
            "image_url": fields["image"],
            "moq": fields.get("moq"),
        })

    return products


def seed_products():
    array_content, js_file = find_products_array()
    products = parse_products(array_content)

    if len(products) != 37:
        raise RuntimeError(
            f"Expected 37 products but found {len(products)}. "
            "Nothing was changed in the database."
        )

    print(f"Found {len(products)} products in {js_file.name}.")
    print("The temporary Test Display Stand record will be replaced.")

    with engine.begin() as connection:
        # Safety check: remove only the known temporary test record.
        connection.execute(
            text("""
                DELETE FROM products
                WHERE name = :test_name
            """),
            {"test_name": "Test Display Stand"},
        )

        # Add the catalogue. IDs are generated by PostgreSQL.
        connection.execute(
            text("""
                INSERT INTO products
                    (name, category, description, image_url, moq)
                VALUES
                    (:name, :category, :description, :image_url, :moq)
            """),
            products,
        )

    print("Catalogue imported successfully!")
    print(f"Products inserted: {len(products)}")
    print("Optional MOQ values are left empty until confirmed.")


if __name__ == "__main__":
    seed_products()
